describe('gpu/style: stored-truth readback, every property (round 35.1)', function () {
  let cy, n, e;

  beforeEach(function () {
    cy = cytoscape({
      elements: [
        { data: { id: 'n1' } },
        { data: { id: 'n2' } },
        { data: { id: 'e1', source: 'n1', target: 'n2' } },
      ],
      style: { nodes: NODE_STYLE, edges: EDGE_STYLE },
    });
    n = cy.$id('n1');
    e = cy.$id('e1');
  });

  it('covers every case label in readProp', function () {
    expect(EXPECTED.length).to.equal(153);
  });

  for (const [prop, onNode, onEdge] of EXPECTED) {
    it(`${prop} reads back the same on a node and an edge`, function () {
      expect(n.style(prop), `node ${prop}`).to.eql(onNode);
      expect(e.style(prop), `edge ${prop}`).to.eql(onEdge);
    });
  }
});
